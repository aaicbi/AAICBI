const { B, log, launch, device, signedIn, clearThrottle } = require('./lib.cjs');
const psql = (q) => require('child_process').execFileSync('/usr/lib/postgresql/16/bin/psql', ['-h','127.0.0.1','-p','5544','-U','dev','-d','aaicbi_dev','-At','-c',q]).toString().trim();
(async () => {
  clearThrottle();
  psql(`update "Course" set published=true, status='PUBLISHED' where id='arena_play'`);
  psql(`update "ArenaConfig" set enabled=true,"gameEnabled"=true where "scopeType"='PLATFORM'`);
  psql(`update "ArenaMatch" set status='CANCELLED' where status in ('PENDING','LOBBY','ACTIVE')`);
  psql(`delete from "UserNotification" where type in ('ARENA_CHALLENGE','ARENA_CHALLENGE_REPLY')`);
  const br = await launch();
  const dev = device('iPhone 7', { viewport: { width: 375, height: 667 } });
  const ca = await signedIn(br, dev, '/api/auth/trainee-login', 't0@dev.test'); const cb = await signedIn(br, dev, '/api/auth/trainee-login', 't1@dev.test');
  const pa = await ca.newPage(); const pb = await cb.newPage(); pb.setDefaultTimeout(12000); pa.setDefaultTimeout(9000);
  // B is elsewhere in the app (not on the arena page); A is in the arena and challenges B
  await pb.goto(`${B}/trainee/dashboard`, { waitUntil: 'load' });
  await pa.goto(`${B}/trainee/arena/arena_play`, { waitUntil: 'load' });
  await pb.waitForTimeout(4000);
  const bId = psql(`select id from "Trainee" where email='t1@dev.test'`);
  const res = await pa.evaluate(async (id) => { const r = await fetch('/api/arena/courses/arena_play/challenge', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ opponentId: id, moduleId: null }) }); return r.status; }, bId);
  log(res === 200, 'a challenge is sent to a player who is elsewhere in the app (' + res + ')');
  await pa.waitForTimeout(800);
  const n = psql(`select count(*) from "UserNotification" where "recipientId"='${bId}' and type='ARENA_CHALLENGE' and "readAt" is null`);
  log(n === '1', 'the challenged player gets a notification in the bell (' + n + ')');
  const title = psql(`select title from "UserNotification" where "recipientId"='${bId}' and type='ARENA_CHALLENGE' limit 1`);
  log(/challenged you/.test(title), 'it says who challenged them: ' + title);
  await pb.getByTestId('challenge-pill').waitFor({ timeout: 30000 });
  log(true, 'the challenged player sees Accept and Decline on screen');
  await pb.screenshot({ path: '/tmp/dev/challenge-pill-phone.png' });
  await pb.getByRole('button', { name: 'Decline' }).click();
  await pb.getByTestId('challenge-pill').waitFor({ state: 'detached' });
  log(true, 'declining from the pill clears it');
  await pa.waitForTimeout(1000);
  const aId = psql(`select id from "Trainee" where email='t0@dev.test'`);
  const reply = psql(`select title from "UserNotification" where "recipientId"='${aId}' and type='ARENA_CHALLENGE_REPLY' limit 1`);
  log(/declined your challenge/.test(reply), 'the challenger is told it was declined: ' + reply);
  const open = psql(`select count(*) from "UserNotification" where "recipientId"='${bId}' and type='ARENA_CHALLENGE' and "readAt" is null`);
  log(open === '0', 'the answered invitation no longer nags from the bell (' + open + ' unread)');
  psql(`update "ArenaMatch" set status='CANCELLED' where status in ('PENDING','LOBBY','ACTIVE')`);
  // someone who is not in the arena at all can still be challenged, and is notified
  psql(`delete from "ArenaPresence" where "traineeId"='${bId}'`);
  psql(`delete from "UserNotification" where "recipientId"='${bId}' and type='ARENA_CHALLENGE'`);
  const off = await pa.evaluate(async (id) => { const r = await fetch('/api/arena/courses/arena_play/challenge', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ opponentId: id, moduleId: null }) }); return { s: r.status, j: await r.json() }; }, bId);
  log(off.s === 200 && off.j.reach === 'none', 'a coursemate who is not in the arena can still be challenged (reach: ' + off.j.reach + ')');
  const n2 = psql(`select count(*) from "UserNotification" where "recipientId"='${bId}' and type='ARENA_CHALLENGE' and "readAt" is null`);
  log(n2 === '1', 'they get the notification while away (' + n2 + ')');
  const mins = psql(`select round(extract(epoch from ("expiresAt" - now()))/60) from "ArenaMatch" where id='${off.j.id}'`);
  log(Number(mins) >= 55, 'the invitation waits about an hour for someone who is away (' + mins + ' min)');
  // nobody answers: when the invitation runs out the challenger is told, once
  psql(`delete from "UserNotification" where type in ('ARENA_CHALLENGE_EXPIRED')`);
  psql(`update "ArenaMatch" set "expiresAt" = now() - interval '1 minute' where id='${off.j.id}'`);
  let got = '0';
  for (let i = 0; i < 14 && got === '0'; i++) {
    await pa.evaluate(() => fetch('/api/arena/active').then((r) => r.status));
    got = psql(`select count(*) from "UserNotification" where "recipientId"='${aId}' and type='ARENA_CHALLENGE_EXPIRED'`);
    if (got === '0') await new Promise((x) => setTimeout(x, 3000));
  }
  log(got === '1', 'the challenger is told when nobody answered in time (' + got + ')');
  const title3 = psql(`select title from "UserNotification" where "recipientId"='${aId}' and type='ARENA_CHALLENGE_EXPIRED' limit 1`);
  log(/didn't answer your challenge/.test(title3), 'it says who did not answer: ' + title3);
  const st = psql(`select status from "ArenaMatch" where id='${off.j.id}'`);
  log(st === 'EXPIRED', 'the invitation is marked expired (' + st + ')');
  const open2 = psql(`select count(*) from "UserNotification" where "recipientId"='${bId}' and type='ARENA_CHALLENGE' and "readAt" is null`);
  log(open2 === '0', 'the lapsed invitation is cleared from the other player\'s bell (' + open2 + ' unread)');
  await new Promise((x) => setTimeout(x, 32000));
  await pa.evaluate(() => fetch('/api/arena/active').then((r) => r.status));
  await new Promise((x) => setTimeout(x, 1000));
  const again = psql(`select count(*) from "UserNotification" where "recipientId"='${aId}' and type='ARENA_CHALLENGE_EXPIRED'`);
  log(again === '1', 'a later sweep does not tell them twice (' + again + ')');
  psql(`update "ArenaMatch" set status='CANCELLED' where status in ('PENDING','LOBBY','ACTIVE')`);
  await br.close();
  const bad = require('./lib.cjs').results.filter((x) => !x[0]);
  console.log(bad.length ? `\n${bad.length} FAILED` : '\nALL PASSED'); process.exit(bad.length ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
